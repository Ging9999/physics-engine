BitmapFont::~BitmapFont() {
    if (m_vao)       glDeleteVertexArrays(1, &m_vao);
    if (m_vbo)       glDeleteBuffers(1, &m_vbo);
    if (m_textureID) glDeleteTextures(1, &m_textureID);
}

void BitmapFont::buildAtlas() {
    // Atlas: 128×64 pixels (kCols=16 chars × 8px wide, kRows=8 char rows × 8px tall)
    const int atlasW = kCols * kCharW;  // 128
    const int atlasH = kRows * kCharH;  // 64
    std::vector<unsigned char> atlas(atlasW * atlasH, 0);

    for (int c = 32; c <= 90; c++) {
        const uint8_t* glyph = kGlyphs[c - 32];
        int col = c % kCols;
        int row = c / kCols;
        for (int gy = 0; gy < kCharH; gy++) {
            for (int gx = 0; gx < kCharW; gx++) {
                bool lit = (glyph[gy] >> (7 - gx)) & 1;
                int px = col * kCharW + gx;
                int py = row * kCharH + gy;
                atlas[py * atlasW + px] = lit ? 255 : 0;
            }
        }
    }
    // Also remap lowercase to uppercase in the atlas
    for (int c = 97; c <= 122; c++) {
        const uint8_t* glyph = kGlyphs[c - 32 - 32]; // uppercase version
        int col = c % kCols;
        int row = c / kCols;
        for (int gy = 0; gy < kCharH; gy++) {
            for (int gx = 0; gx < kCharW; gx++) {
                bool lit = (glyph[gy] >> (7 - gx)) & 1;
                int px = col * kCharW + gx;
                int py = row * kCharH + gy;
                atlas[py * atlasW + px] = lit ? 255 : 0;
            }
        }
    }

    glGenTextures(1, &m_textureID);
    glBindTexture(GL_TEXTURE_2D, m_textureID);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RED, atlasW, atlasH, 0, GL_RED, GL_UNSIGNED_BYTE, atlas.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
}

void BitmapFont::init() {
    buildAtlas();

    glGenVertexArrays(1, &m_vao);
    glGenBuffers(1, &m_vbo);
    glBindVertexArray(m_vao);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
    glBufferData(GL_ARRAY_BUFFER, 0, nullptr, GL_DYNAMIC_DRAW);
    // pos (vec2) + uv (vec2) = 4 floats
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));
    glEnableVertexAttribArray(1);
    glBindVertexArray(0);
}

void BitmapFont::setProjection(Shader& fontShader, int screenW, int screenH) {
    Mat4 proj = Mat4::ortho(0.0f, (float)screenW, 0.0f, (float)screenH, -1.0f, 1.0f);
    fontShader.use();
    fontShader.setMat4("projection", proj);
}

void BitmapFont::drawText(Shader& fontShader, const std::string& text,
                           float x, float y, float scale, const Vec3& color) {
    const int atlasW = kCols * kCharW;
    const int atlasH = kRows * kCharH;

    std::vector<float> verts;
    verts.reserve(text.size() * 6 * 4);

    float cx = x;
    for (char raw : text) {
        unsigned char c = (unsigned char)raw;
        if (c < 32 || c > 126) { cx += kCharW * scale; continue; }

        int col = c % kCols;
        int row = c / kCols;

        float u0 = (float)(col * kCharW)           / atlasW;
        float u1 = (float)(col * kCharW + kCharW)  / atlasW;
        // Flip V: glyph row 0 (top) is stored at buffer top, which is GL V=1
        float v0 = (float)((row + 1) * kCharH) / atlasH;  // bottom of quad = glyph bottom
        float v1 = (float)(row * kCharH)        / atlasH;  // top of quad = glyph top

        float x0 = cx,                  y0 = y;
        float x1 = cx + kCharW * scale, y1 = y + kCharH * scale;

        verts.insert(verts.end(), {
            x0,y0, u0,v0,  x1,y0, u1,v0,  x1,y1, u1,v1,
            x0,y0, u0,v0,  x1,y1, u1,v1,  x0,y1, u0,v1
        });
        cx += kCharW * scale;
    }
    if (verts.empty()) return;

    glBindVertexArray(m_vao);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
    glBufferData(GL_ARRAY_BUFFER, verts.size() * sizeof(float), verts.data(), GL_DYNAMIC_DRAW);

    fontShader.use();
    fontShader.setVec3("textColor", color);
    fontShader.setInt("fontAtlas", 0);

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, m_textureID);

    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glDrawArrays(GL_TRIANGLES, 0, (GLsizei)(verts.size() / 4));

    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);
    glBindVertexArray(0);
}
